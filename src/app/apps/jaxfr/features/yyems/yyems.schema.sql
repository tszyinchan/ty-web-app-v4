CREATE OR REPLACE FUNCTION public.tyapp_yyems_soft_delete_single_record(record_id uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;
  IF NOT public.tyapp_yyems_is_household_member() THEN
    RAISE EXCEPTION 'Not a 525 household member';
  END IF;
  UPDATE public.tyapp_yyems
  SET deleted_at = now()
  WHERE tb_tyapp_yym_id = record_id AND deleted_at IS NULL;
END;
$$;


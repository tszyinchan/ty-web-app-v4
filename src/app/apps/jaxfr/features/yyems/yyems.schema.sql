-- ---------------------------------------------------------------------------
-- RLS: shared household ledger (both bound users see everything)
-- ---------------------------------------------------------------------------

DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'tyapp_yyhome_item_category',
    'tyapp_yyhome_item',
    'tyapp_yyhome_vendor_category',
    'tyapp_yyhome_vendor',
    'tyapp_yyhome_currency',
    'tyapp_yyhome_financial_account',
    'tyapp_yyhome_wallet',
    'tyapp_yyhome_fx_rate',
    'tyapp_yyhome',
    'tyapp_yyhome_bill_share',
    'tyapp_yyhome_price',
    'tyapp_yyhome_buy',
    'tyapp_yyhome_eat',
    'tyapp_yyhome_file'
  ]
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('REVOKE ALL ON public.%I FROM PUBLIC, anon', t);
    IF t = 'tyapp_yyhome_currency' THEN
      EXECUTE format(
        'GRANT SELECT, INSERT, UPDATE ON public.%I TO authenticated',
        t
      );
    ELSE
      EXECUTE format(
        'GRANT SELECT, INSERT, UPDATE ON public.%I TO authenticated',
        t
      );
    END IF;
  END LOOP;
END;
$$;


-- Jaxfr 525 / YYEMS household ledger — phase 1 schema (A+B dictionaries + main cycle).
-- Paste into the Supabase SQL editor after review. Safe to re-run table creates
-- use IF NOT EXISTS; helper functions are CREATE OR REPLACE.
--
-- Does NOT import AppSheet rows. Import comes later (legacy_id mapping).
-- Do NOT store AppSheet auto_* / VC display strings; compute those in the app.
--
-- Access: any tyapp_user with appsheet_525_user_id set, or Super Admin.
-- People: cty/frd from AppSheet map to tyapp_user.user_id (UUID).
-- Shared spend: ownership_user_id IS NULL (legacy Person ID "yyems" is NOT a login).
--
-- Files: Google Drive file id on tyapp_yyems_file (see multimedia strategy).
-- No Supabase Storage in this schema.

-- ---------------------------------------------------------------------------
-- Household gate
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.tyapp_yyems_is_household_member()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT COALESCE(
    public.tyapp_is_super_admin()
    OR EXISTS (
      SELECT 1
      FROM public.tyapp_user u
      WHERE u.user_id = auth.uid()
        AND u.deleted_at IS NULL
        AND u.appsheet_525_user_id IS NOT NULL
        AND length(btrim(u.appsheet_525_user_id)) > 0
    ),
    false
  );
$$;

GRANT EXECUTE ON FUNCTION public.tyapp_yyems_is_household_member() TO authenticated;


-- Jaxfr yyHome household ledger — Phase D schema (tyapp_yyhome_*).
-- Run AFTER yyhome.drop-yyems.sql. Safe-ish to re-run CREATE OR REPLACE pieces;
-- tables use IF NOT EXISTS (drop first if recreating).
--
-- Display name yyHome. App folder/routes still /yyems until a later rename.
-- Access: appsheet_525_user_id, a yyHome / YYEMS feature grant, or Super Admin.
-- People: cty/frd from AppSheet map to tyapp_user.user_id (UUID).
-- Who bears a bill: tyapp_yyhome_bill_share only (no ownership_user_id on the bill).
-- Both = two 0.5 rows. One person = one 1.0 row. Excel party code "yyems" is NOT a login.
--
-- Files: Google Drive file id on tyapp_yyhome_file (see multimedia strategy).
-- No Supabase Storage in this schema.

-- ---------------------------------------------------------------------------
-- Household gate
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.tyapp_yyhome_is_household_member()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT COALESCE(
    public.tyapp_is_super_admin()
    OR EXISTS (
      SELECT 1
      FROM public.tyapp_user u
      WHERE u.user_id = auth.uid()
        AND u.deleted_at IS NULL
        AND u.appsheet_525_user_id IS NOT NULL
        AND length(btrim(u.appsheet_525_user_id)) > 0
    )
    OR EXISTS (
      SELECT 1
      FROM public.tyapp_user_feature_access g
      JOIN public.tyapp_app_feature f
        ON f.tb_tyapp_ap_ftr_id = g.feature_id
      WHERE g.user_id = auth.uid()
        AND f.deleted_at IS NULL
        AND f.name IN ('yyHome', 'YYEMS')
    ),
    false
  );
$$;

GRANT EXECUTE ON FUNCTION public.tyapp_yyhome_is_household_member() TO authenticated;


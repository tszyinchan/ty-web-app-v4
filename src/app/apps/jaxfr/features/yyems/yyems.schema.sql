-- ---------------------------------------------------------------------------
-- RLS: shared household ledger (both bound users see everything)
-- ---------------------------------------------------------------------------

DO $$
DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'tyapp_yyems_item_category',
    'tyapp_yyems_item',
    'tyapp_yyems_vendor_category',
    'tyapp_yyems_vendor',
    'tyapp_yyems_currency',
    'tyapp_yyems_financial_account',
    'tyapp_yyems_wallet',
    'tyapp_yyems_fx_rate',
    'tyapp_yyems',
    'tyapp_yyems_price',
    'tyapp_yyems_buy',
    'tyapp_yyems_eat',
    'tyapp_yyems_file'
  ]
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('REVOKE ALL ON public.%I FROM PUBLIC, anon', t);
    IF t = 'tyapp_yyems_currency' THEN
      EXECUTE format(
        'GRANT SELECT, INSERT, UPDATE ON public.%I TO authenticated',
        t
      );
    ELSE
      EXECUTE format(
        'GRANT SELECT, INSERT, UPDATE ON public.%I TO authenticated',
        t
      );
    END IF;
  END LOOP;
END;
$$;


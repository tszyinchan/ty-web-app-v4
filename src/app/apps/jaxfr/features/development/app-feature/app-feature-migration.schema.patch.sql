-- 5. RLS on tyapp_app_feature — drop ALL existing policies first (this table
--    used to be tyapp_app_category, created directly in Supabase Studio with
--    no committed schema file, so we don't know the old policy names).
-- ---------------------------------------------------------------------------

DO $$
DECLARE
  pol record;
BEGIN
  FOR pol IN
    SELECT policyname FROM pg_policies
    WHERE schemaname = 'public' AND tablename = 'tyapp_app_feature'
  LOOP
    EXECUTE format('DROP POLICY IF EXISTS %I ON public.tyapp_app_feature', pol.policyname);
  END LOOP;
END $$;


-- ============================================================================
-- Migration: App / Feature registry + per-user access control
-- Paste this entire file into the Supabase SQL editor and run top to bottom.
-- Every statement is safe to re-run (idempotent).
--
-- What this does:
--   1. Creates tyapp_app (App registry: Jaxfr / Filelink / Share)
--   2. Renames tyapp_app_category -> tyapp_app_feature and restructures it
--      (drops name_en/name_zh, renames display_name -> name, adds app_id /
--      icon / route / is_admin_only / show_in_launcher)
--   3. Reclassifies the existing rows (which ones are real launcher features
--      vs. legacy/log-only tags) using the real tb_tyapp_ap_ctgy_id values
--      from production
--   4. Renames tyapp_app_log.category_id -> feature_id
--   5. Creates tyapp_user_feature_access + tyapp_user_app_access (grant
--      tables) and migrates tyapp_user.allowed_apps into the latter
--   6. Backfills initial grants so no current user loses access to anything
--      they can already see today
--
-- NOT done here (deliberately): tyapp_user.allowed_apps is NOT dropped yet.
-- The Angular code (guards, login flow) still reads it. We'll drop it in a
-- later patch once that code is migrated to read tyapp_user_app_access.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 0. Shared helper (defensive re-create; already exists from

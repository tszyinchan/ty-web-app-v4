CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

-- ---------------------------------------------------------------------------
-- 1. tyapp_app (App registry)
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.tyapp_app (
  tb_tyapp_app_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tb_tyapp_app_seq_no bigint GENERATED BY DEFAULT AS IDENTITY,
  name text NOT NULL,
  remarks text,
  status smallint NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  CONSTRAINT tyapp_app_name_unique UNIQUE (name)
);

DROP TRIGGER IF EXISTS tyapp_app_set_updated_at ON public.tyapp_app;
CREATE TRIGGER tyapp_app_set_updated_at
  BEFORE UPDATE ON public.tyapp_app
  FOR EACH ROW
  EXECUTE FUNCTION public.set_updated_at();

INSERT INTO public.tyapp_app (name)
SELECT v.name
FROM (VALUES ('Jaxfr'), ('Filelink'), ('Share')) AS v(name)
WHERE NOT EXISTS (
  SELECT 1 FROM public.tyapp_app a WHERE a.name = v.name
);

ALTER TABLE public.tyapp_app ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.tyapp_app FROM PUBLIC, anon;
GRANT SELECT, INSERT, UPDATE ON public.tyapp_app TO authenticated;

DROP POLICY IF EXISTS tyapp_app_select ON public.tyapp_app;
CREATE POLICY tyapp_app_select
  ON public.tyapp_app
  FOR SELECT
  TO authenticated
  USING (deleted_at IS NULL);

DROP POLICY IF EXISTS tyapp_app_write ON public.tyapp_app;

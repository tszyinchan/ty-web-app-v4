CREATE POLICY tyapp_daily_checklist_share_select
  ON public.tyapp_daily_checklist_share
  FOR SELECT
  TO authenticated
  USING (
    deleted_at IS NULL
    AND (owner_user_id = auth.uid() OR viewer_user_id = auth.uid())
  );

CREATE POLICY tyapp_daily_checklist_share_insert
  ON public.tyapp_daily_checklist_share
  FOR INSERT
  TO authenticated
  WITH CHECK (owner_user_id = auth.uid());

CREATE POLICY tyapp_daily_checklist_share_update
  ON public.tyapp_daily_checklist_share
  FOR UPDATE
  TO authenticated
  USING (owner_user_id = auth.uid() AND deleted_at IS NULL)
  WITH CHECK (owner_user_id = auth.uid());

CREATE POLICY tyapp_daily_checklist_day_select
  ON public.tyapp_daily_checklist_day
  FOR SELECT
  TO authenticated
  USING (
    deleted_at IS NULL
    AND (
      user_id = auth.uid()
      OR EXISTS (
        SELECT 1
        FROM public.tyapp_daily_checklist_share s
        WHERE s.owner_user_id = user_id
          AND s.viewer_user_id = auth.uid()
          AND s.deleted_at IS NULL
      )
    )
  );

CREATE POLICY tyapp_daily_checklist_day_insert
  ON public.tyapp_daily_checklist_day
  FOR INSERT
  TO authenticated
  WITH CHECK (user_id = auth.uid());

CREATE POLICY tyapp_daily_checklist_day_update
  ON public.tyapp_daily_checklist_day
  FOR UPDATE
  TO authenticated
  USING (user_id = auth.uid() AND deleted_at IS NULL)
  WITH CHECK (user_id = auth.uid());

CREATE POLICY tyapp_daily_checklist_item_select

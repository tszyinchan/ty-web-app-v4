-- ---------------------------------------------------------------------------
-- Soft-delete RPCs
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.tyapp_daily_checklist_share_soft_delete_single_record(
  record_id uuid
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_found uuid;
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;

  SELECT tb_tyapp_dcl_shr_id
  INTO v_found
  FROM public.tyapp_daily_checklist_share
  WHERE tb_tyapp_dcl_shr_id = record_id
    AND owner_user_id = v_uid
    AND deleted_at IS NULL;

  IF v_found IS NULL THEN
    RAISE EXCEPTION 'Share grant not found or inaccessible';
  END IF;

  UPDATE public.tyapp_daily_checklist_share
  SET deleted_at = now()
  WHERE tb_tyapp_dcl_shr_id = record_id
    AND owner_user_id = v_uid
    AND deleted_at IS NULL;
END;
$$;

GRANT EXECUTE ON FUNCTION public.tyapp_daily_checklist_share_soft_delete_single_record(uuid)
  TO authenticated;

NOTIFY pgrst, 'reload schema';

ALTER TABLE public.tyapp_daily_checklist_share ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.tyapp_daily_checklist_share FROM PUBLIC, anon;
GRANT SELECT, INSERT, UPDATE ON public.tyapp_daily_checklist_share TO authenticated;


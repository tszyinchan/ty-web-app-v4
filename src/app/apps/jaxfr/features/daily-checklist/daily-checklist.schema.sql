CREATE OR REPLACE FUNCTION public.tyapp_daily_checklist_create_from_template(
  target_date date
)
RETURNS SETOF public.tyapp_daily_checklist_item
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_uid uuid := auth.uid();
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;

  IF target_date IS NULL THEN
    RAISE EXCEPTION 'target_date is required';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.tyapp_daily_checklist_item
    WHERE user_id = v_uid
      AND checklist_date = target_date
      AND deleted_at IS NULL
  ) THEN
    RAISE EXCEPTION 'This date already has a checklist. Use standard checklist is only available on an empty date.';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.tyapp_daily_checklist_template_item
    WHERE user_id = v_uid
      AND deleted_at IS NULL
  ) THEN
    RAISE EXCEPTION 'Your Standard Checklist is empty. Add items on the Standard Checklist page first.';
  END IF;

  RETURN QUERY
  WITH src AS (
    SELECT
      t.item_text,
      t.remarks,
      t.sort_order,
      t.tb_tyapp_dcl_tpl_itm_seq_no
    FROM public.tyapp_daily_checklist_template_item t
    WHERE t.user_id = v_uid
      AND t.deleted_at IS NULL
    ORDER BY t.sort_order ASC, t.tb_tyapp_dcl_tpl_itm_seq_no ASC
  ),
  ins AS (
    INSERT INTO public.tyapp_daily_checklist_item (
      user_id,
      checklist_date,
      item_text,
      remarks,
      sort_order,
      status,
      completed_at
    )
    SELECT
      v_uid,
      target_date,
      s.item_text,
      s.remarks,
      s.sort_order,
      1,
      NULL
    FROM src s
    ORDER BY s.sort_order ASC, s.tb_tyapp_dcl_tpl_itm_seq_no ASC
    RETURNING *
  )
  SELECT *
  FROM ins
  ORDER BY sort_order ASC, tb_tyapp_dcl_itm_seq_no ASC;
END;
$$;

CREATE OR REPLACE FUNCTION public.tyapp_daily_checklist_copy_previous_day(
  target_date date
)
RETURNS SETOF public.tyapp_daily_checklist_item
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_source_date date;
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;

  IF target_date IS NULL THEN
    RAISE EXCEPTION 'target_date is required';
  END IF;

  v_source_date := target_date - 1;

  IF EXISTS (
    SELECT 1
    FROM public.tyapp_daily_checklist_item
    WHERE user_id = v_uid
      AND checklist_date = target_date
      AND deleted_at IS NULL
  ) THEN
    RAISE EXCEPTION 'This date already has a checklist. Copy yesterday is only available on an empty date.';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.tyapp_daily_checklist_item
    WHERE user_id = v_uid
      AND checklist_date = v_source_date
      AND deleted_at IS NULL
  ) THEN
    RAISE EXCEPTION 'Yesterday has no active checklist items to copy.';
  END IF;

  RETURN QUERY
  WITH src AS (
    SELECT
      i.item_text,
      i.remarks,
      i.sort_order,
      i.tb_tyapp_dcl_itm_seq_no
    FROM public.tyapp_daily_checklist_item i
    WHERE i.user_id = v_uid
      AND i.checklist_date = v_source_date
      AND i.deleted_at IS NULL
    ORDER BY i.sort_order ASC, i.tb_tyapp_dcl_itm_seq_no ASC
  ),
  ins AS (
    INSERT INTO public.tyapp_daily_checklist_item (
      user_id,
      checklist_date,
      item_text,
      remarks,
      sort_order,
      status,
      completed_at
    )
    SELECT
      v_uid,
      target_date,
      s.item_text,
      s.remarks,
      s.sort_order,
      1,
      NULL
    FROM src s
    ORDER BY s.sort_order ASC, s.tb_tyapp_dcl_itm_seq_no ASC
    RETURNING *
  )
  SELECT *
  FROM ins
  ORDER BY sort_order ASC, tb_tyapp_dcl_itm_seq_no ASC;
END;
$$;

GRANT EXECUTE ON FUNCTION public.tyapp_daily_checklist_create_from_template(date)
  TO authenticated;
GRANT EXECUTE ON FUNCTION public.tyapp_daily_checklist_copy_previous_day(date)
  TO authenticated;


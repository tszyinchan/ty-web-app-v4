-- ---------------------------------------------------------------------------
-- Catalog: reusable item (name, emoji, colour)
-- ---------------------------------------------------------------------------

CREATE TABLE public.tyapp_daily_checklist_item (
  tb_tyapp_dcl_itm_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tb_tyapp_dcl_itm_seq_no bigint GENERATED BY DEFAULT AS IDENTITY,
  user_id uuid NOT NULL REFERENCES auth.users (id),
  item_text text NOT NULL,
  emoji text,
  colour_preset_key text NOT NULL DEFAULT 'slate',
  status smallint NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  CONSTRAINT tyapp_daily_checklist_item_text_not_blank
    CHECK (length(btrim(item_text)) > 0),
  CONSTRAINT tyapp_daily_checklist_item_emoji_len
    CHECK (emoji IS NULL OR length(btrim(emoji)) BETWEEN 1 AND 32),
  CONSTRAINT tyapp_daily_checklist_item_colour_preset
    CHECK (colour_preset_key IN (
      'purple', 'blue', 'teal', 'green', 'gold', 'orange', 'red', 'slate'
    ))
);

CREATE UNIQUE INDEX tyapp_daily_checklist_item_user_name_uniq
  ON public.tyapp_daily_checklist_item (user_id, lower(btrim(item_text)))
  WHERE deleted_at IS NULL;

CREATE INDEX tyapp_daily_checklist_item_user_idx
  ON public.tyapp_daily_checklist_item (user_id)
  WHERE deleted_at IS NULL;

-- ---------------------------------------------------------------------------
-- Day occurrence: one catalog item on one date
-- ---------------------------------------------------------------------------

CREATE TABLE public.tyapp_daily_checklist_day_item (
  tb_tyapp_dcl_day_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tb_tyapp_dcl_day_seq_no bigint GENERATED BY DEFAULT AS IDENTITY,
  user_id uuid NOT NULL REFERENCES auth.users (id),
  item_id uuid NOT NULL REFERENCES public.tyapp_daily_checklist_item (tb_tyapp_dcl_itm_id),
  checklist_date date NOT NULL,
  sort_order integer NOT NULL DEFAULT 0,
  completed_at timestamptz,
  remarks text,
  status smallint NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  CONSTRAINT tyapp_daily_checklist_day_item_sort_order_nonneg
    CHECK (sort_order >= 0)
);

CREATE UNIQUE INDEX tyapp_daily_checklist_day_item_user_date_item_uniq
  ON public.tyapp_daily_checklist_day_item (user_id, checklist_date, item_id)
  WHERE deleted_at IS NULL;

CREATE INDEX tyapp_daily_checklist_day_item_user_date_sort_idx
  ON public.tyapp_daily_checklist_day_item (user_id, checklist_date, sort_order)
  WHERE deleted_at IS NULL;

CREATE INDEX tyapp_daily_checklist_day_item_user_completed_idx
  ON public.tyapp_daily_checklist_day_item (user_id, completed_at)
  WHERE deleted_at IS NULL AND completed_at IS NOT NULL;


-- ---------------------------------------------------------------------------
-- Batch-create RPCs (copy item_id only; skip IDs already on the date)
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.tyapp_daily_checklist_copy_previous_day(
  target_date date
)
RETURNS SETOF public.tyapp_daily_checklist_day_item
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_source_date date;
  v_base integer;
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;

  IF target_date IS NULL THEN
    RAISE EXCEPTION 'target_date is required';
  END IF;

  v_source_date := target_date - 1;

  IF NOT EXISTS (
    SELECT 1
    FROM public.tyapp_daily_checklist_day_item
    WHERE user_id = v_uid
      AND checklist_date = v_source_date
      AND deleted_at IS NULL
  ) THEN
    RAISE EXCEPTION 'Yesterday has no active checklist items to copy.';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.tyapp_daily_checklist_day_item y
    WHERE y.user_id = v_uid
      AND y.checklist_date = v_source_date
      AND y.deleted_at IS NULL
      AND NOT EXISTS (
        SELECT 1
        FROM public.tyapp_daily_checklist_day_item d
        WHERE d.user_id = v_uid
          AND d.checklist_date = target_date
          AND d.item_id = y.item_id
          AND d.deleted_at IS NULL
      )
  ) THEN
    RAISE EXCEPTION 'All of yesterday''s items are already on this date.';
  END IF;

  SELECT COALESCE(MAX(sort_order), -1)
  INTO v_base
  FROM public.tyapp_daily_checklist_day_item
  WHERE user_id = v_uid
    AND checklist_date = target_date
    AND deleted_at IS NULL;

  RETURN QUERY
  WITH src AS (
    SELECT
      y.item_id,
      y.sort_order,
      y.tb_tyapp_dcl_day_seq_no,
      row_number() OVER (
        ORDER BY y.sort_order ASC, y.tb_tyapp_dcl_day_seq_no ASC
      ) AS rn
    FROM public.tyapp_daily_checklist_day_item y
    WHERE y.user_id = v_uid
      AND y.checklist_date = v_source_date
      AND y.deleted_at IS NULL
      AND NOT EXISTS (
        SELECT 1
        FROM public.tyapp_daily_checklist_day_item d
        WHERE d.user_id = v_uid
          AND d.checklist_date = target_date
          AND d.item_id = y.item_id
          AND d.deleted_at IS NULL
      )
  ),
  ins AS (
    INSERT INTO public.tyapp_daily_checklist_day_item (
      user_id,
      item_id,
      checklist_date,
      sort_order,
      status,
      completed_at
    )
    SELECT
      v_uid,
      s.item_id,
      target_date,
      v_base + s.rn::integer,
      1,
      NULL
    FROM src s
    ORDER BY s.rn
    RETURNING *
  )
  SELECT *
  FROM ins
  ORDER BY sort_order ASC, tb_tyapp_dcl_day_seq_no ASC;
END;
$$;

CREATE OR REPLACE FUNCTION public.tyapp_daily_checklist_create_from_standard(
  target_date date
)
RETURNS SETOF public.tyapp_daily_checklist_day_item
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_base integer;
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'Not authenticated';
  END IF;

  IF target_date IS NULL THEN
    RAISE EXCEPTION 'target_date is required';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.tyapp_daily_checklist_standard_item
    WHERE user_id = v_uid
      AND deleted_at IS NULL
  ) THEN
    RAISE EXCEPTION 'Your Standard Checklist is empty. Add items on the Standard Checklist page first.';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.tyapp_daily_checklist_standard_item s
    WHERE s.user_id = v_uid
      AND s.deleted_at IS NULL
      AND NOT EXISTS (
        SELECT 1
        FROM public.tyapp_daily_checklist_day_item d
        WHERE d.user_id = v_uid
          AND d.checklist_date = target_date
          AND d.item_id = s.item_id
          AND d.deleted_at IS NULL
      )
  ) THEN
    RAISE EXCEPTION 'All standard items are already on this date.';
  END IF;

  SELECT COALESCE(MAX(sort_order), -1)
  INTO v_base
  FROM public.tyapp_daily_checklist_day_item
  WHERE user_id = v_uid
    AND checklist_date = target_date
    AND deleted_at IS NULL;

  RETURN QUERY
  WITH src AS (
    SELECT
      s.item_id,
      s.sort_order,
      s.tb_tyapp_dcl_std_seq_no,
      row_number() OVER (
        ORDER BY s.sort_order ASC, s.tb_tyapp_dcl_std_seq_no ASC
      ) AS rn
    FROM public.tyapp_daily_checklist_standard_item s
    WHERE s.user_id = v_uid
      AND s.deleted_at IS NULL
      AND NOT EXISTS (
        SELECT 1
        FROM public.tyapp_daily_checklist_day_item d
        WHERE d.user_id = v_uid
          AND d.checklist_date = target_date
          AND d.item_id = s.item_id
          AND d.deleted_at IS NULL
      )
  ),
  ins AS (
    INSERT INTO public.tyapp_daily_checklist_day_item (
      user_id,
      item_id,
      checklist_date,
      sort_order,
      status,
      completed_at
    )
    SELECT
      v_uid,
      src.item_id,
      target_date,
      v_base + src.rn::integer,
      1,
      NULL
    FROM src
    ORDER BY src.rn
    RETURNING *
  )
  SELECT *
  FROM ins
  ORDER BY sort_order ASC, tb_tyapp_dcl_day_seq_no ASC;
END;
$$;


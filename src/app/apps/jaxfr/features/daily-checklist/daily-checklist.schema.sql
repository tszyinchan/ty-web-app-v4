CREATE TABLE IF NOT EXISTS public.tyapp_daily_checklist_item (
  tb_tyapp_dcl_itm_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tb_tyapp_dcl_itm_seq_no bigint GENERATED BY DEFAULT AS IDENTITY,
  user_id uuid NOT NULL REFERENCES auth.users (id),
  checklist_date date NOT NULL,
  item_text text NOT NULL,
  sort_order integer NOT NULL DEFAULT 0,
  completed_at timestamptz,
  remarks text,
  status smallint NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  CONSTRAINT tyapp_daily_checklist_item_text_not_blank
    CHECK (length(btrim(item_text)) > 0),
  CONSTRAINT tyapp_daily_checklist_item_sort_order_nonneg
    CHECK (sort_order >= 0)
);

CREATE TABLE IF NOT EXISTS public.tyapp_daily_checklist_template_item (
  tb_tyapp_dcl_tpl_itm_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tb_tyapp_dcl_tpl_itm_seq_no bigint GENERATED BY DEFAULT AS IDENTITY,
  user_id uuid NOT NULL REFERENCES auth.users (id),
  item_text text NOT NULL,
  sort_order integer NOT NULL DEFAULT 0,
  remarks text,
  status smallint NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz,
  CONSTRAINT tyapp_daily_checklist_template_item_text_not_blank
    CHECK (length(btrim(item_text)) > 0),
  CONSTRAINT tyapp_daily_checklist_template_item_sort_order_nonneg
    CHECK (sort_order >= 0)
);

CREATE INDEX IF NOT EXISTS tyapp_daily_checklist_item_user_date_sort_idx
  ON public.tyapp_daily_checklist_item (user_id, checklist_date, sort_order)
  WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS tyapp_daily_checklist_item_user_completed_idx
  ON public.tyapp_daily_checklist_item (user_id, completed_at)
  WHERE deleted_at IS NULL AND completed_at IS NOT NULL;

CREATE INDEX IF NOT EXISTS tyapp_daily_checklist_template_item_user_sort_idx
  ON public.tyapp_daily_checklist_template_item (user_id, sort_order)
  WHERE deleted_at IS NULL;

